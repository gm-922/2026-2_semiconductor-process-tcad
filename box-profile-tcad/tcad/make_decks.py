"""Generate Sentaurus Process 1D command files for every planned run.

Usage:
    python3 make_decks.py                       # LSS starting designs (analysis/designs_lss.json)
    python3 make_decks.py --design ../analysis/designs_tcad.json   # after Step 4

Writes decks/<run_id>.cmd and run_list.csv (one row per run, with its purpose).

!! Syntax lines marked VERIFY must be checked against the Sentaurus Process
   user guide of the version installed in class (model names and pdbSet paths
   differ between versions). Everything else is plain sprocess 1D syntax.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """\
# ===== {run_id} : {purpose}
# generated by make_decks.py - edit the generator, not this file
{calibration}
# ---- 1D grid: fine near the surface where the profiles live
line x location=0.0<um>  spacing={fine}<nm>  tag=SiTop
line x location=0.6<um>  spacing={mid}<nm>
line x location=2.0<um>  spacing=20<nm>      tag=SiBottom
region Silicon xlo=SiTop xhi=SiBottom
# n-type (100) substrate, P 1e15 cm-3 (research doc 2-1)
init concentration=1.0e15<cm-3> field=Phosphorus wafer.orient=100   ;# VERIFY: wafer.orient keyword
# ---- diffusion model
# TED on : a point-defect model that tracks implant interstitials (e.g. ChargedPair / ChargedReact)
# TED off: Fermi model (point defects at equilibrium -> no transient enhancement)
pdbSet Silicon Dopant DiffModel {diffmodel}   ;# VERIFY: model names in your version
SetPlxList {{BTotal BActive NetActive}}
"""

IMPLANT = "implant Boron dose={dose:.4g}<cm-2> energy={energy:g}<keV> tilt=7<degree> rotation=22<degree>\n"
ANNEAL = "diffuse temperature={temp:g}<C> time={time:g}<s>\n"
SAVE = "WritePlx {name}.plx\n"


def deck(run_id, purpose, steps, diffmodel="ChargedPair", fine=1.0, mid=2.0, calib=True):
    """steps: list of ('implant', E, Q) | ('anneal', T, t) | ('save', name)."""
    s = HEADER.format(run_id=run_id, purpose=purpose, fine=fine, mid=mid, diffmodel=diffmodel,
                      calibration="AdvancedCalibration   ;# VERIFY: record the version it loads" if calib else "")
    for st in steps:
        if st[0] == "implant":
            s += IMPLANT.format(energy=st[1], dose=st[2])
        elif st[0] == "anneal":
            s += ANNEAL.format(temp=st[1], time=st[2])
        elif st[0] == "save":
            s += SAVE.format(name=st[1])
    return s + "exit\n"


def plan(design: dict):
    runs = []  # (run_id, phase, purpose, steps, kwargs)

    # Step 0 - grid convergence: same implant, four surface spacings
    for sp in (0.5, 1.0, 2.0, 5.0):
        rid = f"S0_grid_{sp:g}nm".replace(".", "p")
        runs.append((rid, "S0 grid", f"80 keV 1e12, surface spacing {sp} nm",
                     [("implant", 80, 1e12), ("save", rid)], dict(fine=sp, mid=max(sp, 2.0))))

    # Step 1 - single-energy sweep, unit dose 1e12, as-implanted
    energies = sorted({20, 30, 40, 50, 80, 100, 130, 150, 170}
                      | {float(e) for d in design.values() for e in d["energies_kev"]})
    for e in energies:
        rid = f"S1_B_{e:g}keV"
        runs.append((rid, "S1 sweep", f"single implant {e:g} keV, 1e12",
                     [("implant", e, 1e12), ("save", rid)], {}))

    # Step 1b - dose linearity at 80 keV
    for q in (4e12, 1e13):
        rid = f"S1b_B_80keV_{q:.0e}".replace("+", "")
        runs.append((rid, "S1b linearity", f"80 keV at {q:.0e}: is profile/dose the same as at 1e12?",
                     [("implant", 80, q), ("save", rid)], {}))

    # Step 2 - superposition check (2-implant design, as-implanted)
    d2 = design["2"]
    rid = "S2_superpose_2x"
    runs.append((rid, "S2 superposition", "2x design implanted back to back; compare with sum of S1 singles",
                 [("implant", e, q) for e, q in sorted(zip(d2["energies_kev"], d2["doses_cm2"]), reverse=True)]
                 + [("save", rid)], {}))

    # Step 5 - multi-implant designs, as-implanted (n = 1..4)
    for n, d in design.items():
        rid = f"S5_{n}x_asimpl"
        order = sorted(zip(d["energies_kev"], d["doses_cm2"]), reverse=True)  # high energy first
        runs.append((rid, "S5 multi", f"{n}x design as-implanted",
                     [("implant", e, q) for e, q in order] + [("save", rid)], {}))

    # Step 6 - anneal sequences A / B / C x TED on/off, n = 2..4, 1050 C 10 s per RTA
    T, t = 1050, 10
    for n in ("2", "3", "4"):
        order = sorted(zip(design[n]["energies_kev"], design[n]["doses_cm2"]), reverse=True)
        k = len(order)
        seqs = {
            "A": [s for e, q in order for s in (("implant", e, q), ("anneal", T, t))],
            "B": [("implant", e, q) for e, q in order] + [("anneal", T, t)],
            "C": [("implant", e, q) for e, q in order] + [("anneal", T, t * k)],
        }
        for sq, steps in seqs.items():
            for model, tag in (("ChargedPair", "TEDon"), ("Fermi", "TEDoff")):
                rid = f"S6_{n}x_{sq}_{tag}"
                runs.append((rid, "S6 anneal", f"{n}x, sequence {sq}, {T} C {t} s per RTA, {tag}",
                             steps + [("save", rid)], dict(diffmodel=model)))

    # Step 6b - thermal-budget sweep on the 4x design, sequence B, TED on
    order = sorted(zip(design["4"]["energies_kev"], design["4"]["doses_cm2"]), reverse=True)
    for T, t in ((1050, 10), (1050, 60), (1050, 300), (1000, 1800)):
        rid = f"S6b_4x_B_{T}C_{t}s"
        runs.append((rid, "S6b budget", f"4x, sequence B, {T} C {t} s",
                     [("implant", e, q) for e, q in order] + [("anneal", T, t), ("save", rid)], {}))
    return runs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--design", default=str(HERE.parent / "analysis" / "designs_lss.json"))
    ap.add_argument("--out", default=str(HERE / "decks"))
    args = ap.parse_args()
    design = json.loads(Path(args.design).read_text())
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    runs = plan(design)
    with open(HERE / "run_list.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["run_id", "phase", "purpose", "deck"])
        for rid, phase, purpose, steps, kw in runs:
            (out / f"{rid}.cmd").write_text(deck(rid, purpose, steps, **kw))
            w.writerow([rid, phase, purpose, f"decks/{rid}.cmd"])
    print(f"{len(runs)} decks -> {out}, list -> {HERE / 'run_list.csv'}")


if __name__ == "__main__":
    main()
